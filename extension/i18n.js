export const LANG_LABELS = { fr: 'FR', en: 'EN', es: 'ES', zh: '中文' }

export function detectExtensionLang(stored) {
  if (LANGS.includes(stored)) return stored
  const nav = (navigator.language || 'fr').toLowerCase()
  if (nav.startsWith('en')) return 'en'
  if (nav.startsWith('es')) return 'es'
  if (nav.startsWith('zh')) return 'zh'
  return 'fr'
}

export function translate(lang, key, vars) {
  const dict = DICT[lang] ?? DICT.fr
  const template = dict[key] ?? DICT.fr[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  )
}

/** Applique les traductions aux éléments portant data-i18n* dans un conteneur. */
export function applyTranslations(root, lang) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = translate(lang, element.dataset.i18n)
  })
  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', translate(lang, element.dataset.i18nPlaceholder))
  })
  root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', translate(lang, element.dataset.i18nAriaLabel))
  })
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.setAttribute('title', translate(lang, element.dataset.i18nTitle))
  })
  document.documentElement.lang = lang
}

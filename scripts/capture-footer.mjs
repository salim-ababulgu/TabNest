import { chromium } from "playwright"
const b = await chromium.launch()
async function run(name, w, h, dark) {
  const p = await b.newPage({ viewport: { width: w, height: h } })
  await p.addInitScript((d) => localStorage.setItem("tabnest-theme", d), dark ? "dark" : "light")
  await p.goto("http://localhost:5173/", { waitUntil: "networkidle" })
    await p.getByRole("button", { name: /Créer un compte gratuit|Create a free account/ }).first().click()
  await p.waitForTimeout(600)
  await p.getByRole("tab", { name: /^Connexion$/ }).click()
  await p.locator("#password").fill(process.env.TABNEST_DEMO_PASSWORD ?? '')
  await p.getByRole("button", { name: /^Se connecter$/ }).click()
  await p.getByText(/Ce qui compte revient|What matters comes back/).waitFor({ timeout: 20000 })
  await p.waitForTimeout(800)
  await p.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
  await p.waitForTimeout(600)
  await p.screenshot({ path: `public/screenshots/${name}.png` })
  await p.close()
}
await run("footer-dashboard-1280", 1280, 900, false)
await run("footer-dashboard-390", 390, 844, false)
await run("footer-dashboard-dark", 1280, 900, true)
await b.close()
